import { matchesThemeText } from './searchTags';

// 「学びの多様化学校は公立の学校」のように、特定の学校名ではなく制度・施設の種類そのもの
// について、AIが古い・不正確な一般知識で断定してしまう問題への対応（2026-10-21追加）。
//
// lib/schoolFacts.tsは「個別の学校名」が相談文に出てきた場合に、その学校の確認済み情報を
// 渡す仕組みだが、「学びの多様化学校ってフリースクールと何が違うの？」のような、特定の
// 学校名を伴わない一般論の質問にはこれが効かない。このファイルは同じ考え方を「制度・施設の
// 種類」のレベルに広げたもので、相談文に該当のキーワードが出てきたら、学校名の有無に
// 関わらず、確認済みのファクトを渡す。
//
// 運用方針：ここに書く事実は、裏取りが取れている・制度上明確なものに限る（費用のように
// 幅がある項目は「レンジ」「傾向」として書き、断定しない）。新たに「AIがこの制度についてまた
// 間違えた」というケースが見つかったら、プロンプトの注意書きを増やすのではなく、まずこの
// ファイルに1項目追記することを検討する。

export type InstitutionKey = '学びの多様化学校' | 'フリースクール' | '通信制高校' | '教育支援センター';

// 検出に使うテーマ語（lib/searchTags.tsのcanonical word・同義語をそのまま流用する）。
// 「学びの多様化学校」はsearchTags.ts側ではcanonical wordが「不登校特例校」で、
// 「学びの多様化学校」はその同義語として登録されているため、検出もそちらを使う
// （lib/searchTags.ts THEME_SYNONYMS参照）。
const DETECT_WORD: Record<InstitutionKey, string> = {
  学びの多様化学校: '不登校特例校',
  フリースクール: 'フリースクール',
  通信制高校: '通信制高校',
  教育支援センター: '教育支援センター',
};

