// AIの回答（または相談文）の中に、小児科・心療内科・児童精神科など「医療機関への
// 受診」を示唆する語が出てきた場合に、/support内の「思春期外来（児童精神科など）」
// セクションへの案内カードを出すかどうかを判定する（2026-11-19追加）。
//
// きっかけ：睡眠・食欲の変化など心身の不調に触れたAIの回答で「学校のスクールカウンセラーや
// 小児科・心療内科に相談してみるのも選択肢です」という一文が出た際に、「こういう回答後に、
// 思春期外来とかの情報だしてあげれたらいいな、近くの」との指摘を受けた。
//
// 「近くの」という要望ではあるが、相談内容からは居住地が分からず、このサイトの
// 思春期外来リスト自体も現時点では東京都・大阪府の一部しかカバーできていない
// （lib/data/adolescentClinics.ts参照）。そのため、この判定では「医療機関への相談を
// 促す文脈かどうか」だけを検出し、実際の地域選択・近さの判断は/support側のUI
// （都道府県ごとのセクション）に委ねる。案内カード側の文言でも、現時点のカバー範囲の
// 限定を正直に明記する（lib/schoolFacts.ts等、他の案内ブロックと同じく「確認できている
// 範囲の情報」という立て付けを踏襲）。
//
// 「スクールカウンセラー」単独では学校内の相談窓口止まりで医療機関受診の文脈とは
// 限らないため、キーワードには含めない（頻出語のため、含めると表示されすぎて
// かえって埋もれる）。医療機関そのものを指す語に限定する。
const CLINIC_KEYWORDS = [
  '思春期外来',
  '児童精神科',
  '小児精神科',
  '心療内科',
  '精神科',
  'メンタルクリニック',
  '小児科',
  '発達検査',
  'WISC',
];

export function shouldShowClinicSuggestion(texts: (string | null | undefined)[]): boolean {
  const joined = texts.filter(Boolean).join('\n');
  if (!joined) return false;
  return CLINIC_KEYWORDS.some((kw) => joined.includes(kw));
}
