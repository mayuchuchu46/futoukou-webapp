// 自動投稿（サンプル相談）の質問文生成に関する共通処理（2026-10-17追加）。
// もともとapp/api/cron/auto-post/route.tsに直接書いていたが、「過去に自動投稿した
// 分も含めて、質問文がAIっぽく同じ人が書いたように見えるので直したい」との指摘を
// 受けて、cron（新規投稿）と管理画面からの再生成（既存投稿の作り直し）の両方から
// 同じロジックを使えるよう、ここに切り出した。
//
// 2026-10-14・2026-10-16の対応（トーンのランダム化、直近の投稿との言い回し重複回避）
// だけでは「文章の書かれ方そのもの（文の長さ・整い方・構成の順番）」が毎回似ており、
// 結果として「同じ人が書いている」ように見える点が残っていた。そのため今回、
// (1) 話し方のトーンに加えて「どんな状況で書いたか（執筆シチュエーション）」の軸を
// 追加し、文の長さ・整い方にもばらつきを持たせた
// (2) 直近の参考件数を5件→8件に増やし、重複回避の精度を上げた
// (3) 書き出し方・構成の順番をランダムに指示する項目を追加した

export const TONE_STYLES = [
  '少し硬め・丁寧な言葉遣い（「〜でしょうか」「〜かと思います」など）',
  'くだけた話し言葉に近いトーン（「〜なんです」「〜で困ってます」など）',
  '疲れ・焦りがにじむ短めの文（句読点少なめ、率直な言い方）',
  '状況を客観的に淡々と説明するトーン（感情語を抑えめに）',
  '困惑・戸惑いが前面に出たトーン（「どうしたらいいのか分からず」など）',
];

// 「どんな状況・書き方で投稿したか」の軸（2026-10-17追加）。トーン（話し方）とは別に、
// 文章の長さ・整い方・構成にばらつきを持たせるための軸。これが無いと、トーンを変えても
// 結局「2〜4文・整った構成」という同じ型にはまり、同じ人が書いたように見えてしまう。
// 2026-10-17、「もっと短くしたほうがいい」との指摘を受けて、全体的に文の数を
// 短く調整（最長でも3文程度まで。従来は4〜5文のパターンもあった）。
export const SITUATION_STYLES = [
  '夜遅く、疲れた状態でスマホから手早く入力した（1文だけで終わってもよい）',
  '昼間、少し時間をとって落ち着いて書いた（2〜3文程度）',
  '仕事や家事の合間に、立ったまま急いで書いた（1〜2文。言葉が足りない部分があってもよい）',
  '何度か書き直しながら、丁寧に言葉を選んで書いた（2〜3文）',
  '思いつくままに、とりとめなく書いた（2文程度。話が多少飛ぶ、句読点が少なめ）',
  '端的に、要点だけを短く書いた（1文だけ。説明は最小限）',
];

// 書き出し・構成の順番のバリエーション（2026-10-17追加）。「状況説明→心情」という
// 同じ順番に偏らないよう、明示的にパターンを与えてランダムに選ばせる。
export const STRUCTURE_STYLES = [
  '状況の説明から書き始める',
  '今の気持ち・心情から書き始める',
  '子ども本人の言動・様子から書き始める',
  '聞きたいこと（質問）そのものから単刀直入に書き始める',
  '直近に起きた具体的な出来事（一度きりのこと）から書き始める',
];

export function pickRandom<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

// カテゴリ例文（CATEGORY_EXAMPLES）と直近の投稿を踏まえて、自動投稿の質問文生成
// プロンプトを組み立てる。cron（新規投稿）・管理画面の再生成の両方から呼ぶ共通処理。
export function buildAutoSeedQuestionPrompt(
  catLabel: string,
  categoryExample: string,
  grade: string | null,
  gender: string | null,
  recentQuestions: string[]
): string {
  const tone = pickRandom(TONE_STYLES);
  const situation = pickRandom(SITUATION_STYLES);
  const structure = pickRandom(STRUCTURE_STYLES);

  return `あなたは、不登校の子を持つ保護者を演じて、相談サイトに投稿する相談文を1つ書くタスクを行います。
テーマ：${catLabel}
${grade ? `お子さんの学年：${grade}\n` : ''}${gender ? `性別：${gender}\n` : ''}
文章のトーン（話し方）：${tone}
執筆シチュエーション（文の長さ・整い方に反映させる）：${situation}
書き出し・構成の順番：${structure}

このテーマで書かれそうな内容の例（内容・言い回しともそのまま使わないこと。あくまでテーマのイメージ）：
${categoryExample}
${
  recentQuestions.length
    ? `\n直近に投稿した相談文（これらと書き出し・文末表現・言い回し・文章の長さが似ないようにすること）：\n${recentQuestions.map((q) => `- ${q}`).join('\n')}`
    : ''
}

条件：
- 全体で3文以内に収めること（1文だけでもよい）。長々と説明しない
- 文章の長さ・整い方は、上記の「執筆シチュエーション」の指定にはっきり反映させること（毎回同じくらいの長さ・同じくらい整った文章にしない）
- 保護者が実際に書きそうな、具体的でリアルな内容にする
- 「〜ようになりました」「〜について悩んでいます」のような、AIが多用しがちな定型的な結び方を毎回使わない
- 深刻すぎる・極端な内容（希死念慮・自傷・虐待等）は書かない
- 実在の学校名・地名・個人名は含めない
- 出力は相談文の本文のみ。前置き・タイトル・カギカッコは不要`;
}
