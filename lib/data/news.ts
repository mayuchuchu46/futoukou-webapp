// 不登校関連の最新ニュースまとめ（/news、2026-10-29追加）。
//
// 【掲載方針】
// - 著作権のあるニュース記事本文はそのまま転載しない。titleは当サイト側で
//   つけた見出し（元記事の見出しをそのままコピーしない）、summaryは当サイトが
//   自分の言葉で書いた2〜3文程度の要約にする。元記事を読みたい人はsourceUrlから
//   直接飛んでもらう（＝「紹介＋出典リンク」の形。lib/data/freeSchools.ts等の
//   noteと同じ「確認できた事実だけを書く」方針を、ニュースにも適用する）。
// - 「不登校」に直接関係する内容かどうかを確認できたものだけを載せる（タイトルに
//   それっぽい単語が入っているだけで中身が関係ない記事、推測で「不登校に関係
//   しそう」と判断したものは載せない。ユーザーの「適当な推測はなし、正確な情報
//   だけを述べる」という方針に合わせる）。
// - 一次情報（文部科学省・自治体・学校法人等の発表）が確認できる場合はそちらを
//   sourceUrlにする。報道のみの場合は、信頼できる報道機関の記事をsourceUrlにする。
// - dateは記事の公開日（確認できる場合）。確認できない場合はaddedAt（当サイトが
//   掲載した日）のみを使う。
// - 新しい順（配列の先頭が最新）に並べる。
export type NewsItem = {
  id: string; // 一意なID（スラッグ形式、他データの重複チェック用）
  date: string | null; // 記事の公開日（YYYY-MM-DD）。確認できない場合はnull
  addedAt: string; // 当サイトへの掲載日（YYYY-MM-DD）
  title: string; // 当サイト側でつけた見出し（元記事見出しのコピーではない）
  summary: string; // 当サイトが自分の言葉で書いた要約
  sourceName: string; // 出典名（報道機関名・発表元名）
  sourceUrl: string;
  category: 'policy' | 'research' | 'local' | 'other'; // policy=制度・施策、research=調査・統計、local=自治体の取組、other=その他
  // 記事中に数値の比較（○○は○%、△△は△%、など）が含まれる場合のみ設定する簡単な
  // グラフ用データ（2026-10-29追加、「記事内容にあったグラフを出したい」との要望を
  // 受けて）。数値はsummary・出典で確認できた事実のみを入れる（推測で作らない）。
  // 2〜3項目程度の単純な比較を想定（app/today/page.tsxの集計バーと同じ見た目で表示）。
  stats?: { label: string; value: number; unit: string }[];
  // statsグラフの上に出す短い説明文（2026-10-29追加、「この割合が何なのかも
  // わかるようにテキストを入れたい」との要望を受けて）。単位が%のときに自動で出る
  // 「全体を100%としたときの割合」だけでは、何の100%なのか（不登校の子ども全体の
  // うち、なのか、学年ごとの不登校の子どものうち、なのか等）が伝わらないため、
  // 記事ごとに具体的な説明を書く。statsを設定する記事には必ず設定する。
  statsCaption?: string;
  // 記事の中で一番インパクトのある数字（2026-10-29追加、「わかりやすいインパクトある
  // 数字を見せつつ、バズりを意識した画像がいい」との要望を受けて）。個別記事ページ
  // （/news/[id]）とそのシェア用OGP画像で、大きな文字で見せる「見出し数字」として使う。
  // valueは記事・出典で確認できた数字（または、その数字から機械的に計算できる比率）
  // のみとし、推測で作った数字は入れない。
  headline?: { value: string; label: string };
  // マナプリ（manapri.net）側で、このニュースに関連して書いたコラムへのリンク
  // （2026-10-29追加、「このニュースに関連するコラム、という感じでマナプリで書いて、
  // ここに貼るのがいいんじゃない？相互リンクでさ」との提案を受けて）。
  // マナプリ側の記事は当サイトのCMSの外（別サイト）で公開するため、ここでは
  // 公開済みのURLを手動で設定する運用にする（コラム自体の下書きはプロジェクトの
  // ドキュメントで管理）。未設定（undefined）の間は、個別記事ページ側で
  // 「関連コラム」欄ごと表示しない（存在しないリンクを置かない）。
  relatedColumn?: { title: string; url: string };
};

