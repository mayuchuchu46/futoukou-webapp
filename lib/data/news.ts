// 不登校関連の最新ニュースまとめ（/news、2026-10-29追加）。
//
// 【掲載方針】
// - 著作権のあるニュース記事本文はそのまま転載しない。titleは当サイト側で
//   つけた見出し（元記事の見出しをそのままコピーしない）、summaryは当サイトが
//   自分の言葉で書いた2〜3文程度の要約にする。元記事を読みたい人はsourceUrlから
//   直接飛んでもらう（＝「紹介＋出典リンク」の形。lib/data/freeSchools.ts等の
//   noteと同じ「確認できた事実だけを書く」方針を、ニュースにも適用する）。
// - 「不登校」に直接関係する内容かどうかを確認できたものだけを載せる（タイトルに
//   それっぽい単語が入っているだけで中身が関係ない記事、推測で「不登校に関係
//   しそう」と判断したものは載せない。ユーザーの「適当な推測はなし、正確な情報
//   だけを述べる」という方針に合わせる）。
// - 一次情報（文部科学省・自治体・学校法人等の発表）が確認できる場合はそちらを
//   sourceUrlにする。報道のみの場合は、信頼できる報道機関の記事をsourceUrlにする。
// - dateは記事の公開日（確認できる場合）。確認できない場合はaddedAt（当サイトが
//   掲載した日）のみを使う。
// - 新しい順（配列の先頭が最新）に並べる。
export type NewsItem = {
  id: string; // 一意なID（スラッグ形式、他データの重複チェック用）
  date: string | null; // 記事の公開日（YYYY-MM-DD）。確認できない場合はnull
  addedAt: string; // 当サイトへの掲載日（YYYY-MM-DD）
  title: string; // 当サイト側でつけた見出し（元記事見出しのコピーではない）
  summary: string; // 当サイトが自分の言葉で書いた要約
  sourceName: string; // 出典名（報道機関名・発表元名）
  sourceUrl: string;
  category: 'policy' | 'research' | 'local' | 'other'; // policy=制度・施策、research=調査・統計、local=自治体の取組、other=その他
};

export const NEWS_ITEMS: NewsItem[] = [];
