// 専門家の「経歴確認」機能で使う、実務分野の選択肢（2026-11-03追加）。
// 田村さん（臨床・資格面のアドバイザー）からの提案：
// 「負担少なめにするなら、複数のプルダウンメニューで、児童福祉分野、障害福祉分野、
// 保健医療分野、産業分野、教育分野と選択でき、その横に空欄で『〜年』と手入力するのが
// 良いかと。個人プロフィールにそのまま経歴としてあるとよいかなと。」を受けて実装。
// 資格確認（登録証アップロード）とは別に、実務経験の分野・年数を本人の自己申告で
// 入力してもらい、公開プロフィールに経歴として表示する（運営による裏付け確認は行わない、
// 低負担の自己申告ベース）。経験者（先輩保護者）には資格を前提とする分野の選択肢は
// 合わないため、この機能は専門家向けのみに提供する。
