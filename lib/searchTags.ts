// テーマ語＋その同義語をまとめて返す。
export function getThemeSearchWords(word: string): string[] {
  return [word, ...(THEME_SYNONYMS[word] || [])];
}

// 1件の投稿本文（question・answerなど1フィールド分）が、テーマ語またはその同義語の
// いずれかを含むかどうかを判定する（一覧カード・詳細ページの「関連テーマ」表示で使用）。
export function matchesThemeText(text: string | null | undefined, word: string): boolean {
  if (!text) return false;
  return getThemeSearchWords(word).some((w) => text.includes(w));
}

// Supabaseの.or()にそのまま渡せる、テーマ語＋同義語ぶんのilike条件をまとめて返す
// （question・answerの両カラムに対して、どの語でも一致すればOKとするOR条件）。
export function buildThemeOrFilter(word: string): string {
  return getThemeSearchWords(word)
    .map((w) => `question.ilike.%${w}%,answer.ilike.%${w}%`)
    .join(',');
}
